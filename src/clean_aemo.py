"""Clean the raw AEMO NSW 2013 file into a minimal dataset.

Input:
data/raw/aemo_nsw_2013.csv: raw AEMO price and demand export generated by the fetch script or supplied externally.

Output:
data/cleaned/aemo_cleaned.csv: a cleaned dataset containing the timestamp, price, and total demand.

aemo_cleaned.csv:

 Column            Description                                               
 DATETIME_30MIN    timestamp for the 30-minute settlement interval           
 PRICE_AUD_MWH     settlement price in Australian dollars per megawatt-hour  
 DEMAND_MW         total electricity demand in megawatts                     
"""

import pandas as pd
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
CLEANED_DATA_DIR = DATA_DIR / "cleaned"
RAW_DATA_DIR = DATA_DIR / "raw"

CLEANED_DATA_DIR.mkdir(parents=True, exist_ok=True)

def clean_aemo():
    print("Cleaning AEMO data...")
    aemo_path = RAW_DATA_DIR / "aemo_nsw_2013.csv"
    df = pd.read_csv(aemo_path)

    print("Selecting relevant columns and converting timestamps...")
    df = df[['SETTLEMENTDATE', 'RRP', 'TOTALDEMAND']]
    df['SETTLEMENTDATE'] = pd.to_datetime(df['SETTLEMENTDATE'])
    
    print("Renaming columns to its metric units...")
    # Standardize column naming and metric measurement units
    df = df.rename(columns={
        'SETTLEMENTDATE': 'DATETIME_30MIN',
        'RRP': 'PRICE_AUD_MWH',
        'TOTALDEMAND': 'DEMAND_MW'
    })
    
    print("Dropping N/A values...")
    df = df.dropna()

    out_path = CLEANED_DATA_DIR / "aemo_cleaned.csv"
    
    print(f"Saving cleaned AEMO data to {out_path}...")
    df.to_csv(out_path, index=False)

    print(f"Cleaned AEMO saved to {out_path}")

if __name__ == "__main__":
    clean_aemo()